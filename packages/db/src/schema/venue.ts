import { sql } from 'drizzle-orm';
import {
  char,
  check,
  index,
  pgTable,
  smallint,
  text,
  timestamp,
  uuid,
} from 'drizzle-orm/pg-core';
import { user } from './auth.js';
import { geographyPoint } from './geography.js';

// Domain tables use snake_case columns (Better Auth tables keep camelCase).
// Enum-like values mirror @arenaz/contracts (CANCELLATION_POLICIES).

export const venue = pgTable(
  'venue',
  {
    id: uuid('id').primaryKey().default(sql`gen_random_uuid()`),
    ownerId: text('owner_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    slug: text('slug').notNull().unique(),
    name: text('name').notNull(),
    description: text('description'),
    phone: text('phone').notNull(),
    cep: text('cep').notNull(),
    street: text('street').notNull(),
    number: text('number').notNull(),
    complement: text('complement'),
    neighborhood: text('neighborhood').notNull(),
    city: text('city').notNull(),
    state: char('state', { length: 2 }).notNull(),
    location: geographyPoint('location').notNull(),
    // The public API works ONLY on this point (the exact one is private):
    // `location` snapped to a 0.01 degree grid (about 1 km). Generated by the
    // database, so it can never drift from `location`.
    approxLocation: geographyPoint('approx_location')
      .notNull()
      .generatedAlwaysAs(
        sql`ST_SnapToGrid(location::geometry, 0.01)::geography`,
      ),
    amenities: text('amenities').array().notNull().default(sql`'{}'::text[]`),
    cancellationPolicy: text('cancellation_policy').notNull(),
    // IANA zone (BRAZIL_TIMEZONES in @arenaz/contracts). Wall-clock times of
    // the venue (hours, price rules, bookings) are read in this zone.
    timezone: text('timezone').notNull(),
    status: text('status').notNull().default('draft'),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index('venue_owner_id_idx').on(t.ownerId),
    index('venue_location_idx').using('gist', t.location),
    index('venue_approx_location_idx').using('gist', t.approxLocation),
    check(
      'venue_cancellation_policy_check',
      sql`${t.cancellationPolicy} in ('flexivel', 'moderada', 'rigida')`,
    ),
    check('venue_status_check', sql`${t.status} in ('draft', 'published')`),
    // Keep in sync with BRAZIL_TIMEZONES (a contracts test parses migration 0006).
    check(
      'venue_timezone_check',
      sql`${t.timezone} in ('America/Sao_Paulo', 'America/Bahia', 'America/Fortaleza', 'America/Recife', 'America/Maceio', 'America/Belem', 'America/Araguaina', 'America/Manaus', 'America/Boa_Vista', 'America/Porto_Velho', 'America/Cuiaba', 'America/Campo_Grande', 'America/Rio_Branco', 'America/Noronha', 'America/Santarem', 'America/Eirunepe')`,
    ),
  ],
);

export const venueHours = pgTable(
  'venue_hours',
  {
    id: uuid('id').primaryKey().default(sql`gen_random_uuid()`),
    venueId: uuid('venue_id')
      .notNull()
      .references(() => venue.id, { onDelete: 'cascade' }),
    weekday: smallint('weekday').notNull(),
    openMinute: smallint('open_minute').notNull(),
    closeMinute: smallint('close_minute').notNull(),
  },
  (t) => [
    // Several intervals per weekday (a shift past midnight is two of them).
    index('venue_hours_venue_id_weekday_idx').on(t.venueId, t.weekday),
    check('venue_hours_weekday_check', sql`${t.weekday} between 0 and 6`),
    check(
      'venue_hours_range_check',
      sql`${t.openMinute} >= 0 and ${t.closeMinute} <= 1440 and ${t.openMinute} < ${t.closeMinute}`,
    ),
    check(
      'venue_hours_step_check',
      sql`${t.openMinute} % 30 = 0 and ${t.closeMinute} % 30 = 0`,
    ),
  ],
);

export const venuePhoto = pgTable(
  'venue_photo',
  {
    id: uuid('id').primaryKey().default(sql`gen_random_uuid()`),
    venueId: uuid('venue_id')
      .notNull()
      .references(() => venue.id, { onDelete: 'cascade' }),
    storageKey: text('storage_key').notNull().unique(),
    // Not unique: reordering would fight a unique constraint.
    position: smallint('position').notNull(),
    // Widths of the resized WebP variants the worker made (PHOTO_VARIANT_WIDTHS
    // in @arenaz/contracts, only those smaller than the original; `{}` for a
    // small photo). NULL = still pending: the worker picks these rows up.
    variantWidths: smallint('variant_widths').array(),
    // Failed variant runs; the worker gives up at 3 and the original is served.
    variantAttempts: smallint('variant_attempts').notNull().default(0),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index('venue_photo_venue_id_idx').on(t.venueId),
    // Only the pending rows, which the worker polls every few seconds.
    index('venue_photo_variants_pending_idx')
      .on(t.createdAt)
      .where(sql`${t.variantWidths} is null`),
  ],
);

export type Venue = typeof venue.$inferSelect;
export type NewVenue = typeof venue.$inferInsert;
export type VenueHours = typeof venueHours.$inferSelect;
export type VenuePhoto = typeof venuePhoto.$inferSelect;
export type NewVenuePhoto = typeof venuePhoto.$inferInsert;
