'use client';

import {
  formatCents,
  paymentChargeSchema,
  paymentResultSchema,
  type PaymentCharge,
} from '@arenaz/contracts';
import { Alert, Button, buttonClasses, cn } from '@arenaz/ui';
import { AppLink } from '@/components/ui/next-link';
import { useRouter } from 'next/navigation';
import { useCallback, useEffect, useRef, useState, useTransition } from 'react';
import { apiSend } from '@/lib/api-client';
import { Countdown } from './countdown';

export interface PixPaymentProps {
  bookingId: string;
  /** The server's deadline for this hold. */
  holdExpiresAt: string;
  venueSlug: string;
  /** What the QR charges (the booking total, centavos). */
  totalCents: number;
  /** The server's clock at render time; see `Countdown`. */
  serverNow?: string | undefined;
}

type ChargeState =
  | { status: 'loading' }
  | { status: 'error'; message: string }
  | { status: 'ready'; charge: PaymentCharge };

/**
 * The QR is generated by the server. It is shown through an `<img>` with a
 * data URI, never injected as markup: an image cannot run scripts.
 */
function qrSource(svg: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

/** How often the page asks the server whether the payment arrived. */
const POLL_MS = 5000;
/** Two checks closer than this are one (tab shown and window focused). */
const MIN_GAP_MS = 1000;

const FOCUS =
  'focus-visible:outline-2 focus-visible:outline-offset-[3px] focus-visible:outline-ink';

/** Pix payment of a held booking: QR, "copia e cola", countdown, simulation. */
export function PixPayment({
  bookingId,
  holdExpiresAt,
  venueSlug,
  totalCents,
  serverNow,
}: PixPaymentProps) {
  const router = useRouter();
  const [state, setState] = useState<ChargeState>({ status: 'loading' });
  // Which render of the page the local clock gave up on. A refreshed page
  // that still says "held" has a new stamp, which makes the payment payable
  // again (the local clock was ahead of the server).
  const stamp = `${holdExpiresAt}|${serverNow ?? ''}`;
  const [expiredStamp, setExpiredStamp] = useState<string | null>(null);
  const expired = expiredStamp === stamp;
  const [copied, setCopied] = useState(false);
  const [copyError, setCopyError] = useState('');
  const [showCode, setShowCode] = useState(false);
  const [payError, setPayError] = useState<string | undefined>();
  const [paying, setPaying] = useState(false);
  // StrictMode runs effects twice; one charge per page view is enough.
  const requested = useRef(false);

  // "Aguardando pagamento…" is true: while the charge is pending and the hold
  // is live the page asks the server again every few seconds, and when the
  // tab is shown or focused again, so a payment made elsewhere (another tab,
  // later the PSP's webhook) turns the page into the confirmed one. The
  // refresh runs in a transition: `refreshing` stays true until the new page
  // arrives, and no second refresh starts meanwhile. Stops on expiry (the
  // countdown's own refresh tells the server's side), when the booking is no
  // longer held (the page stops rendering this) and on unmount.
  const [refreshing, startRefresh] = useTransition();
  const refreshingRef = useRef(false);
  const routerRef = useRef(router);
  const lastCheck = useRef(0);
  useEffect(() => {
    refreshingRef.current = refreshing;
    routerRef.current = router;
  });
  const polling = state.status === 'ready' && expiredStamp !== stamp;
  useEffect(() => {
    if (!polling) return;
    const check = () => {
      if (document.visibilityState !== 'visible' || refreshingRef.current) {
        return;
      }
      // Coming back to a tab fires "visibilitychange" and "focus" together.
      const now = Date.now();
      if (now - lastCheck.current < MIN_GAP_MS) return;
      lastCheck.current = now;
      startRefresh(() => {
        // Returned on purpose: the transition lasts as long as the refresh.
        // eslint-disable-next-line @typescript-eslint/no-confusing-void-expression
        return routerRef.current.refresh();
      });
    };
    const timer = setInterval(check, POLL_MS);
    document.addEventListener('visibilitychange', check);
    window.addEventListener('focus', check);
    return () => {
      clearInterval(timer);
      document.removeEventListener('visibilitychange', check);
      window.removeEventListener('focus', check);
    };
  }, [polling]);

  const load = useCallback(async () => {
    setState({ status: 'loading' });
    const result = await apiSend(
      'POST',
      `/bookings/${bookingId}/payment`,
      undefined,
      paymentChargeSchema,
    );
    setState(
      result.ok
        ? { status: 'ready', charge: result.data }
        : { status: 'error', message: result.message },
    );
    // The booking is gone or no longer waiting: the server says what it is now.
    if (!result.ok && (result.status === 404 || result.status === 409)) {
      router.refresh();
    }
  }, [bookingId, router]);

  useEffect(() => {
    if (requested.current) return;
    requested.current = true;
    void load();
  }, [load]);

  const onExpire = useCallback(
    (live: boolean) => {
      setExpiredStamp(stamp);
      // The server tells whether it really expired. Only when it ran out
      // while watching: a page that arrives already expired would refresh
      // forever if the API clock lags this one.
      if (live) router.refresh();
    },
    [router, stamp],
  );

  async function copy(code: string) {
    // Clear first, so repeating the copy is announced again.
    setCopied(false);
    setCopyError('');
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
    } catch {
      // The code opens, so it can be selected and copied by hand.
      setShowCode(true);
      setCopyError(
        'Não foi possível copiar. Selecione o código e copie manualmente.',
      );
    }
  }

  async function simulate(chargeId: string) {
    setPayError(undefined);
    setPaying(true);
    const result = await apiSend(
      'POST',
      `/payments/fake/${encodeURIComponent(chargeId)}/pay`,
      undefined,
      paymentResultSchema,
    );
    if (!result.ok) {
      setPaying(false);
      setPayError(result.message);
      if (result.status === 404 || result.status === 409) router.refresh();
      return;
    }
    // Stays busy: the page reloads as a confirmed booking.
    router.refresh();
  }

  return (
    <section
      aria-labelledby="pagamento-pix"
      className="flex flex-col items-center gap-[18px] border-t border-line px-5 pt-6 pb-6 text-center"
    >
      <h2
        id="pagamento-pix"
        className="font-wordmark text-[22px] font-bold tracking-[-0.02em]"
      >
        Pague com Pix
      </h2>
      <Countdown
        // Each render of the page brings its own server clock, and a
        // countdown fixes its skew when it mounts: a new page, a new one.
        key={stamp}
        expiresAt={holdExpiresAt}
        serverNow={serverNow}
        onExpire={onExpire}
      />

      {expired ? (
        <AppLink
          href={`/espacos/${encodeURIComponent(venueSlug)}`}
          className={buttonClasses({
            variant: 'primary',
            className: 'w-full',
          })}
        >
          Escolher outro horário
        </AppLink>
      ) : state.status === 'loading' ? (
        <p role="status" className="text-sm text-muted">
          Gerando o Pix…
        </p>
      ) : state.status === 'error' ? (
        <div className="flex w-full flex-col items-center gap-3 text-left">
          <Alert tone="error">{state.message}</Alert>
          <Button variant="secondary" onClick={() => void load()}>
            Tentar de novo
          </Button>
        </div>
      ) : (
        <>
          <div className="rounded-[26px] border border-line bg-bg p-[18px] shadow-2">
            {/* eslint-disable-next-line @next/next/no-img-element -- a data URI, nothing for next/image to optimize */}
            <img
              src={qrSource(state.charge.qrCodeSvg)}
              alt="QR code do Pix. Escaneie com o app do seu banco."
              width={220}
              height={220}
              className="block size-[220px]"
            />
          </div>
          <p className="font-wordmark text-[28px] font-bold tracking-[-0.03em]">
            {formatCents(totalCents)}
          </p>
          <button
            type="button"
            onClick={() => {
              void copy(state.charge.copyPaste);
            }}
            className={cn(
              'flex h-[52px] w-full items-center justify-center gap-2.5 rounded-2xl border border-ink bg-bg text-[15px] font-semibold text-ink transition-colors duration-150 hover:bg-surface motion-reduce:transition-none',
              FOCUS,
            )}
          >
            <svg
              width="18"
              height="18"
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="2"
              strokeLinecap="round"
              strokeLinejoin="round"
              aria-hidden="true"
            >
              <rect x="9" y="9" width="12" height="12" rx="2" />
              <path d="M5 15V5a2 2 0 0 1 2-2h10" />
            </svg>
            {copied ? 'Código copiado' : 'Copiar código'}
          </button>
          {/* Always in the page, so a change of text is spoken. */}
          <p
            role="status"
            className={copyError ? 'text-sm text-ink' : 'sr-only'}
          >
            {copyError || (copied ? 'Código copiado' : '')}
          </p>
          <details
            open={showCode}
            onToggle={(event) => {
              setShowCode(event.currentTarget.open);
            }}
            className="w-full text-sm text-muted"
          >
            <summary
              className={cn(
                'mx-auto flex min-h-11 w-fit cursor-pointer items-center rounded-button px-2 underline underline-offset-2',
                FOCUS,
              )}
            >
              Ver o código copia e cola
            </summary>
            <code className="mt-1 block w-full rounded-button bg-surface px-3 py-2 text-center font-mono text-sm break-all text-ink select-all">
              {state.charge.copyPaste}
            </code>
          </details>
          <p className="flex items-center gap-2.5 text-sm text-muted">
            <span
              aria-hidden="true"
              className="size-2 rounded-full bg-[#e3a008] shadow-[0_0_0_4px_rgba(227,160,8,0.18)]"
            />
            Aguardando pagamento…
          </p>
          {state.charge.simulatable ? (
            <div className="flex w-full flex-col gap-3 pt-2">
              <p className="text-sm text-muted">
                Ambiente de teste: nenhum dinheiro de verdade é movimentado.
              </p>
              <Alert tone="error">{payError}</Alert>
              <button
                type="button"
                disabled={paying}
                aria-busy={paying ? true : undefined}
                onClick={() => {
                  void simulate(state.charge.chargeId);
                }}
                className={cn(
                  'h-[52px] w-full rounded-2xl border border-dashed border-line-control bg-transparent text-sm font-medium text-muted transition-colors duration-150 enabled:hover:bg-surface disabled:cursor-not-allowed disabled:opacity-60 motion-reduce:transition-none',
                  FOCUS,
                )}
              >
                Simular pagamento
                {paying ? <span className="sr-only">, Aguarde…</span> : null}
              </button>
            </div>
          ) : null}
        </>
      )}
    </section>
  );
}
