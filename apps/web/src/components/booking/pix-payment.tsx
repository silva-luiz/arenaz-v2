'use client';

import {
  paymentChargeSchema,
  paymentResultSchema,
  type PaymentCharge,
} from '@arenaz/contracts';
import { Alert, Button, buttonClasses } from '@arenaz/ui';
import { AppLink } from '@/components/ui/next-link';
import { useRouter } from 'next/navigation';
import { useCallback, useEffect, useRef, useState } from 'react';
import { apiSend } from '@/lib/api-client';
import { Countdown } from './countdown';

export interface PixPaymentProps {
  bookingId: string;
  /** The server's deadline for this hold. */
  holdExpiresAt: string;
  venueSlug: string;
}

type ChargeState =
  | { status: 'loading' }
  | { status: 'error'; message: string }
  | { status: 'ready'; charge: PaymentCharge };

/**
 * The QR is generated by the server. It is shown through an `<img>` with a
 * data URI, never injected as markup: an image cannot run scripts.
 */
function qrSource(svg: string): string {
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

/** Pix payment of a held booking: QR, "copia e cola", countdown, simulation. */
export function PixPayment({
  bookingId,
  holdExpiresAt,
  venueSlug,
}: PixPaymentProps) {
  const router = useRouter();
  const [state, setState] = useState<ChargeState>({ status: 'loading' });
  const [expired, setExpired] = useState(false);
  const [copyMessage, setCopyMessage] = useState('');
  const [payError, setPayError] = useState<string | undefined>();
  const [paying, setPaying] = useState(false);
  // StrictMode runs effects twice; one charge per page view is enough.
  const requested = useRef(false);

  const load = useCallback(async () => {
    setState({ status: 'loading' });
    const result = await apiSend(
      'POST',
      `/bookings/${bookingId}/payment`,
      undefined,
      paymentChargeSchema,
    );
    setState(
      result.ok
        ? { status: 'ready', charge: result.data }
        : { status: 'error', message: result.message },
    );
  }, [bookingId]);

  useEffect(() => {
    if (requested.current) return;
    requested.current = true;
    void load();
  }, [load]);

  const onExpire = useCallback(() => {
    setExpired(true);
    // The server now shows the booking as expired.
    router.refresh();
  }, [router]);

  async function copy(code: string) {
    try {
      await navigator.clipboard.writeText(code);
      setCopyMessage('Código copiado');
    } catch {
      setCopyMessage(
        'Não foi possível copiar. Selecione o código e copie manualmente.',
      );
    }
  }

  async function simulate(chargeId: string) {
    setPayError(undefined);
    setPaying(true);
    const result = await apiSend(
      'POST',
      `/payments/fake/${encodeURIComponent(chargeId)}/pay`,
      undefined,
      paymentResultSchema,
    );
    if (!result.ok) {
      setPaying(false);
      setPayError(result.message);
      return;
    }
    // Stays busy: the page reloads as a confirmed booking.
    router.refresh();
  }

  return (
    <section aria-label="Pagamento com Pix" className="flex flex-col gap-4">
      <Countdown expiresAt={holdExpiresAt} onExpire={onExpire} />

      {expired ? (
        <AppLink
          href={`/espacos/${encodeURIComponent(venueSlug)}`}
          className={buttonClasses({ variant: 'primary' })}
        >
          Escolher outro horário
        </AppLink>
      ) : state.status === 'loading' ? (
        <p role="status" className="text-sm text-muted">
          Gerando o Pix…
        </p>
      ) : state.status === 'error' ? (
        <div className="flex flex-col gap-3">
          <Alert tone="error">{state.message}</Alert>
          <Button
            variant="secondary"
            className="self-start"
            onClick={() => {
              void load();
            }}
          >
            Tentar de novo
          </Button>
        </div>
      ) : (
        <>
          <div className="flex flex-col items-center gap-4">
            {/* eslint-disable-next-line @next/next/no-img-element -- a data URI, nothing for next/image to optimize */}
            <img
              src={qrSource(state.charge.qrCodeSvg)}
              alt="QR code do Pix. Escaneie com o app do seu banco."
              width={208}
              height={208}
              className="size-52 rounded-photo border border-line bg-white p-2"
            />
            <p className="text-sm text-muted">Ou use o Pix copia e cola:</p>
            <code className="w-full rounded-button bg-surface px-3 py-2 text-center font-mono text-sm break-all select-all">
              {state.charge.copyPaste}
            </code>
          </div>
          <Button
            variant="secondary"
            onClick={() => {
              void copy(state.charge.copyPaste);
            }}
          >
            Copiar código
          </Button>
          <p role="status" className="min-h-5 text-sm text-ink">
            {copyMessage}
          </p>
          {state.charge.simulatable ? (
            <div className="flex flex-col gap-3 border-t border-line pt-4">
              <p className="text-sm text-muted">
                Ambiente de teste: nenhum dinheiro de verdade é movimentado.
              </p>
              <Alert tone="error">{payError}</Alert>
              <Button
                loading={paying}
                onClick={() => {
                  void simulate(state.charge.chargeId);
                }}
              >
                Simular pagamento
              </Button>
            </div>
          ) : null}
        </>
      )}
    </section>
  );
}
